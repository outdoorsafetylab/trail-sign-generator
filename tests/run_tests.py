#!/usr/bin/env python3
"""Regression tests for generate.py and generate.rb.

Inkscape, pdfunite and Ghostscript are replaced by stand-ins in tests/fakebin,
so a run compares the SVG each generator writes before vectorizing, which is
where every CSV value, hidden layer and fill color ends up.

1. Every trail spec is generated by both generators and each output SVG is
   compared with the SHA-256 recorded in tests/expected/<py|rb>.sha256. Those
   signs have been printed, so their output must not change. After an
   intended change, review the differences, then run with --update.
2. Small fixtures check what the trail data does not exercise: reprints,
   blank padding, hidden and recolored self-closing elements, and the inputs
   that must stop a run.

The repository is copied to a temporary directory first, so the working
tree's output/ directories are never touched.

Usage: python3 tests/run_tests.py [--update]
"""

import glob
import hashlib
import os
import shutil
import subprocess
import sys
import tempfile
import xml.dom.minidom

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TESTS = os.path.join(ROOT, "tests")
EXPECTED = os.path.join(TESTS, "expected")
GENERATORS = {
    "py": [sys.executable, "generate.py"],
    "rb": ["ruby", "generate.rb"],
}

failures = []


def fail(message):
    failures.append(message)
    print(f"FAIL {message}")


def copy_repo(dest):
    files = subprocess.run(
        ["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
        cwd=ROOT, check=True, capture_output=True,
    ).stdout.decode("utf-8").split("\0")
    for rel in filter(None, files):
        src = os.path.join(ROOT, rel)
        if not os.path.isfile(src):
            continue
        os.makedirs(os.path.dirname(os.path.join(dest, rel)), exist_ok=True)
        shutil.copy2(src, os.path.join(dest, rel))


def run(gen, spec, cwd, *flags):
    env = dict(os.environ, PATH=os.path.join(TESTS, "fakebin") + os.pathsep + os.environ["PATH"])
    return subprocess.run(
        GENERATORS[gen] + [spec, *flags], cwd=cwd, env=env, capture_output=True, text=True,
    )


def intermediate_dir(cwd, spec):
    with open(os.path.join(cwd, spec), encoding="utf-8") as f:
        out = yaml.safe_load(f)["output"]["dir"]
    return os.path.join(cwd, os.path.dirname(spec), out, "intermediate")


def svgs(directory):
    return sorted(glob.glob(os.path.join(directory, "*.svg")))


def check_well_formed(label, paths):
    for path in paths:
        try:
            xml.dom.minidom.parse(path)
        except Exception as e:  # noqa: BLE001 - any parse error is a failure
            fail(f"{label}: {os.path.basename(path)} is not well-formed XML: {e}")
            return


def trail_specs(cwd):
    return sorted(
        os.path.relpath(p, cwd)
        for p in glob.glob(os.path.join(cwd, "*", "*.yaml"))
        if os.path.basename(os.path.dirname(p)) not in ("tests", "docker")
    )


def check_trails(cwd, update):
    os.makedirs(EXPECTED, exist_ok=True)
    for gen in GENERATORS:
        actual = {}
        for spec in trail_specs(cwd):
            result = run(gen, spec, cwd)
            if result.returncode != 0:
                fail(f"{gen} {spec}: exit {result.returncode}\n{result.stderr}")
                continue
            out = intermediate_dir(cwd, spec)
            paths = svgs(out)
            check_well_formed(f"{gen} {spec}", paths)
            for path in paths:
                key = f"{spec[:-len('.yaml')]}/{os.path.basename(path)}"
                with open(path, "rb") as f:
                    actual[key] = hashlib.sha256(f.read()).hexdigest()
            shutil.rmtree(os.path.dirname(out))
        manifest = os.path.join(EXPECTED, f"{gen}.sha256")
        if update:
            with open(manifest, "w", encoding="utf-8") as f:
                for key in sorted(actual):
                    f.write(f"{actual[key]}  {key}\n")
            print(f"wrote {os.path.relpath(manifest, ROOT)} ({len(actual)} files)")
            continue
        expected = {}
        with open(manifest, encoding="utf-8") as f:
            for line in f:
                digest, key = line.rstrip("\n").split("  ", 1)
                expected[key] = digest
        changed = [k for k in sorted(expected) if k in actual and actual[k] != expected[k]]
        missing = [k for k in sorted(expected) if k not in actual]
        added = [k for k in sorted(actual) if k not in expected]
        for name, keys in (("changed", changed), ("missing", missing), ("new", added)):
            if keys:
                fail(f"{gen}: {len(keys)} {name} output file(s), e.g. {', '.join(keys[:5])}")
        if not (changed or missing or added):
            print(f"ok   {gen}: {len(actual)} trail output files match")


def fixture_spec(cwd, name, data, **input_extra):
    spec = {
        "input": {
            "template": "template.svg",
            "data": data,
            "mask": "mask.svg",
            "preview_layers": ["Layer 3"],
            "hide_when_empty": {"地標名稱": "mileage_bar"},
            "blank_template": "blank.svg",
            "fill": {"background_color": {"主線": "#ffff00", "支線": "#f58635"}},
            **input_extra,
        },
        "output": {
            "dir": f"output_{name}",
            "prefix": f"{name}_",
            "w": 40,
            "h": 40,
            "slot": {"x": 0, "y": 0, "w": 10, "h": 10, "repeat": {"x": 2, "y": 2}},
        },
    }
    path = os.path.join("tests", "fixtures", f"{name}.yaml")
    with open(os.path.join(cwd, path), "w", encoding="utf-8") as f:
        yaml.safe_dump(spec, f, allow_unicode=True)
    return path


def check_fixtures(cwd):
    signs_of = lambda out: [p for p in svgs(out) if os.path.basename(p).startswith("sign_")]
    read = lambda p: open(p, encoding="utf-8").read()
    for gen in GENERATORS:
        spec = fixture_spec(cwd, "reprints", ["data.csv"], reprints="reprints.csv")
        result = run(gen, spec, cwd, "--hide-preview-layers")
        if result.returncode != 0:
            fail(f"{gen} fixture reprints: exit {result.returncode}\n{result.stderr}")
            continue
        out = intermediate_dir(cwd, spec)
        paths = svgs(out)
        check_well_formed(f"{gen} fixture reprints", paths)
        signs = [read(p) for p in signs_of(out)]
        # 4 data rows + 2 reprints = 6, padded with blanks to 2 pages of 2x2.
        if len(signs) != 8:
            fail(f"{gen} fixture reprints: expected 8 signs, got {len(signs)}")
            continue
        if signs[4] != signs[1] or signs[5] != signs[0]:
            fail(f"{gen} fixture reprints: reprinted signs differ from their source signs")
        if "空白" not in signs[6] or "空白" not in signs[7]:
            fail(f"{gen} fixture reprints: last two signs are not blank padding")
        if 'fill="#f58635"' not in signs[3] or 'fill="#ffff00"' not in signs[0]:
            fail(f"{gen} fixture reprints: background not recolored by 路線名稱")
        bar = lambda s: s[s.index('id="mileage_bar"'):].split(">", 1)[0]
        if "display:none" not in bar(signs[1]) or "display:none" in bar(signs[0]):
            fail(f"{gen} fixture reprints: mileage_bar not hidden exactly when 地標名稱 is empty")
        layer = signs[0][signs[0].index("<g "):].split(">", 1)[0]
        if "display:none" not in layer:
            fail(f"{gen} fixture reprints: preview layer not hidden with --hide-preview-layers")
        shutil.rmtree(os.path.dirname(out))

        stops = [
            ("nomatch", ["data.csv"], {"reprints": "reprints_nomatch.csv"}, "No sign"),
            ("differ", ["data.csv"], {"reprints": "reprints_differ.csv"}, "print differently"),
            ("unknown", ["data.csv"], {"reprints": "reprints_unknown.csv"}, "Unknown column"),
            ("mismatch", ["data.csv", "mismatch.csv"], {}, "header mismatch"),
        ]
        for name, data, extra, message in stops:
            spec = fixture_spec(cwd, name, data, **extra)
            result = run(gen, spec, cwd)
            if result.returncode == 0 or message not in result.stderr:
                fail(f"{gen} fixture {name}: expected a non-zero exit with '{message}', "
                     f"got exit {result.returncode}\n{result.stderr}")
    if not any(f.startswith(("py fixture", "rb fixture")) for f in failures):
        print("ok   fixtures: reprints, padding, hiding, recoloring and stopping inputs")


def main():
    update = "--update" in sys.argv[1:]
    with tempfile.TemporaryDirectory() as tmp:
        copy_repo(tmp)
        check_trails(tmp, update)
        if not update:
            check_fixtures(tmp)
    if failures:
        print(f"\n{len(failures)} failure(s)")
        sys.exit(1)


if __name__ == "__main__":
    main()
